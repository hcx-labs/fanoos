import { createCipheriv } from "node:crypto";
import type { Subtitle } from "@tube/shared";

export type CaptionTrack = {
  languageCode?: string;
  kind?: string;
  vssId?: string;
  name?: { simpleText?: string; runs?: { text: string }[] };
};
export type CaptionSelection = { video: string; label: string; instance: "a" | "s"; expires: number };

/** The proxy accepts selectors, never caller-supplied upstream URLs or paths. */
export function validCaptionSelection(value: unknown, now = Date.now()): value is CaptionSelection {
  if (!value || typeof value !== "object") return false;
  const v = value as CaptionSelection;
  return typeof v.video === "string" && /^[\w-]{11}$/.test(v.video)
    && typeof v.label === "string" && v.label.length > 0 && v.label.length <= 1000
    && (v.instance === "a" || v.instance === "s")
    && Number.isSafeInteger(v.expires) && v.expires > now && v.expires <= now + 6 * 3600_000;
}

/** Companion SERVER_VERIFY_REQUESTS uses AES-128-ECB of timestamp|videoId. */
export function companionCaptionPath(selection: CaptionSelection, secret: string, now = Date.now()): string {
  const query = new URLSearchParams({ label: selection.label });
  if (Buffer.byteLength(secret) === 16) {
    const cipher = createCipheriv("aes-128-ecb", Buffer.from(secret), null);
    query.set("check", Buffer.concat([cipher.update(`${Math.round(now / 1000)}|${selection.video}`), cipher.final()]).toString("base64url"));
  }
  return `/companion/api/v1/captions/${selection.video}?${query}`;
}

export function captionSubtitles(tracks: CaptionTrack[], url: (label: string) => string): (Subtitle & { id: string; autoGenerated: boolean })[] {
  const names = tracks.map((t) => t.name?.simpleText ?? t.name?.runs?.map((r) => r.text).join("") ?? "");
  return tracks.flatMap((track, index) => {
    const name = names[index]!;
    // Companion selects by exact label, not vssId. Don't advertise ambiguous selectors.
    if (!name || name.length > 1000 || names.filter((n) => n === name).length !== 1 || !track.languageCode) return [];
    let locale: string;
    try { locale = Intl.getCanonicalLocales(track.languageCode)[0]!; } catch { return []; }
    const autoGenerated = track.kind === "asr";
    return [{ id: `${autoGenerated ? "asr" : "manual"}:${track.vssId ?? locale}:${index}`, locale,
      label: autoGenerated && !/\bauto[- ]generated\b/i.test(name) ? `${name} (auto-generated)` : name, autoGenerated, format: "vtt" as const, url: url(name) }];
  });
}

/** Reject HTML/error bodies even when an upstream mistakenly responds 200. */
export async function fetchCaptionVtt(url: string, signal: AbortSignal, headers: Record<string, string> = {}): Promise<string> {
  const response = await fetch(url, { headers, redirect: "error", signal: AbortSignal.any([signal, AbortSignal.timeout(30_000)]) });
  if (!response.ok) { await response.body?.cancel(); throw new Error("Caption upstream failed"); }
  const text = await response.text();
  if (!/^\uFEFF?WEBVTT(?:[ \t\r\n]|$)/.test(text)) throw new Error("Invalid VTT response");
  return text;
}
