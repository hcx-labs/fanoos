test("audio metadata exposes display name, BCP47 language and default role", () => {
  assert.deepEqual(audioMetadata({ id: "en-US.4", displayName: "English (original)", audioIsDefault: true }), { label: "English (original)", lang: "en-US", role: "main" });
  assert.deepEqual(audioMetadata({ id: "fr.1", displayName: "French dub", audioIsDefault: false }), { label: "French dub", lang: "fr", role: "alternate" });
  assert.equal(audioMetadata(undefined).role, "main");
  assert.equal(xmlEscape('A & B < "dub"'), "A &amp; B &lt; &quot;dub&quot;");
});
