// Dedicated headless Chrome + local Vite only; fixtures intercept API traffic.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { send, evaluate, on, close } from './cdp.mjs';
const waitFor = condition => evaluate(`new Promise((resolve,reject)=>{const start=performance.now();function check(){if(${condition})return resolve();if(performance.now()-start>10000)return reject(Error('Player tracks check timed out'));requestAnimationFrame(check)}check()})`);
try {
  await send('Page.enable');
  await send('Page.addScriptToEvaluateOnNewDocument', { source: readFileSync(new URL('./fixture.js', import.meta.url), 'utf8') + `
  (()=>{const original=window.fetch;window.fetch=async(input,init)=>{
    if(new URL(input,location.href).pathname==='/api/me/data' && init?.method==='PUT') window.__savedPlayerData=JSON.parse(init.body).data;
    const response=await original(input,init);
    if(new URL(input,location.href).pathname.startsWith('/api/v/youtube/videos/')){
      const page=await response.json();
      page.stream={progressive:'data:video/mp4;base64,',subtitles:[
        {id:'en-asr',locale:'en-US',label:'English auto',autoGenerated:true,format:'vtt',url:'data:text/vtt,WEBVTT%0A%0A00:00.000%20--%3E%2000:10.000%0AAutomatic'},
        {id:'en-manual',locale:'en-US',label:'English manual',format:'vtt',url:'data:text/vtt,WEBVTT%0A%0A00:00.000%20--%3E%2000:10.000%0AManual'}]};
      return Response.json(page);
    }return response;
  }})();` });
  const loaded = new Promise(resolve => on('Page.loadEventFired', resolve));
  await send('Page.navigate', { url: process.env.PERF_URL || 'http://127.0.0.1:5190/' });
  await loaded;
  await waitFor(`document.querySelector('a[href="/watch/youtube/v0"]')`);
  await evaluate(`document.querySelector('a[href="/watch/youtube/v0"]').click()`);
  await waitFor(`document.querySelector('video')`);
  await evaluate(`document.querySelector('video').dispatchEvent(new Event('play'));document.querySelector('[aria-label$="(c)"]').click()`);
  await waitFor(`document.querySelector('[role="menu"]')`);
  const select = async label => {
    await evaluate(`Array.from(document.querySelectorAll('[role="menu"] button')).find(b=>b.textContent.trim()===${JSON.stringify(label)}).click()`);
    await evaluate(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
  };
  await select('English auto');
  assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('video track')).map(t=>[t.label,t.srclang,t.track.mode])`), [['English auto', 'en-US', 'showing']]);
  await waitFor(`window.__savedPlayerData?.languages?.subtitles==='en-US'`);
  await evaluate(`window.__oldTrack=document.querySelector('video track')`);
  await select('English manual');
  assert.equal(await evaluate(`window.__oldTrack.track.mode`), 'disabled');
  assert.equal(await evaluate(`window.__oldTrack.isConnected`), false);
  assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('video track')).map(t=>[t.label,t.track.mode])`), [['English manual', 'showing']]);
  await select('Off');
  assert.equal(await evaluate(`document.querySelectorAll('video track').length`), 0);
  await waitFor(`window.__savedPlayerData?.languages?.subtitles===''`);
  assert.equal(await evaluate(`document.querySelectorAll('.JASSUB').length`), 0);
  console.log('PASS: same-language ASR/manual native VTT selection, disabled cleanup, explicit off');
} finally { close(); }
