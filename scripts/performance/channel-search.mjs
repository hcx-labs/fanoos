import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { send, evaluate, on, close } from "./cdp.mjs";
const waitFor = condition => evaluate(`new Promise((resolve,reject)=>{const start=performance.now();function check(){if(${condition})return resolve();if(performance.now()-start>10000)return reject(Error('Search check timed out'));requestAnimationFrame(check)}check()})`);
await send("Page.enable");
await send("Page.addScriptToEvaluateOnNewDocument", { source: readFileSync(new URL("./fixture.js", import.meta.url), "utf8") + `
(() => {
 const original=window.fetch;
 window.__channelQueries=[];
 window.fetch=async(input,init)=>{
   const url=new URL(input,location.href);
   const response=await original(input,init);
   if(url.pathname!=='/api/v/youtube/channels/c0')return response;
   const page=await response.json();
   const all=await (await original('/api/feed')).json();
   const query=url.searchParams.get('q')||'',sort=url.searchParams.get('sort')||'new',next=url.searchParams.get('next');
   window.__channelQueries.push({query,sort,next});
   if(query==='pending')await new Promise(resolve=>window.__releaseSearch=resolve);
   const start=query?500:sort==='popular'?400:0;
   page.videos=all.slice(start+(next?2:0),start+(next?4:2));
   page.next=next?undefined:query?'search-cursor':sort==='popular'?'popular-cursor':'latest-cursor';
   return Response.json(page);
 };
})();` });
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
const loaded = new Promise(resolve => on("Page.loadEventFired",resolve));
await send("Page.navigate", { url: process.env.PERF_URL || "http://127.0.0.1:5190/" });
await loaded;
await waitFor(`document.querySelector('a[href="/channel/youtube/c0"]')`);
await evaluate(`document.querySelector('a[href="/channel/youtube/c0"]').click()`);
await waitFor(`document.querySelector('h1')?.textContent==='Channel 0' && document.querySelectorAll('article').length===2`);
const tab = name => evaluate(`[...document.querySelectorAll('[role="tab"]')].find(el=>el.textContent==='${name}').dispatchEvent(new MouseEvent('mousedown',{bubbles:true,button:0}))`);
const more = () => evaluate(`[...document.querySelectorAll('button')].find(el=>el.textContent==='Load more videos').click()`);
const submit = async query => {
  await evaluate(`{const input=document.querySelector('input[aria-label="Search channel videos"]');input.focus();input.select();}`);
  await send("Input.insertText", { text: query });
  await evaluate(`document.querySelector('form[aria-label="Search this channel"]').requestSubmit()`);
};
await tab("Popular");
await waitFor(`document.querySelector('article')?.textContent.includes('video 400')`);
await more();
await waitFor(`document.querySelectorAll('article').length===4`);
assert.deepEqual(await evaluate(`window.__channelQueries.at(-1)`), {query:"",sort:"popular",next:"popular-cursor"});
await submit("ancient");
await waitFor(`document.querySelector('article')?.textContent.includes('video 500') && document.querySelectorAll('article').length===2`);
assert.deepEqual(await evaluate(`window.__channelQueries.at(-1)`), {query:"ancient",sort:"new",next:null});
await more();
await waitFor(`document.querySelectorAll('article').length===4`);
assert.deepEqual(await evaluate(`window.__channelQueries.at(-1)`), {query:"ancient",sort:"new",next:"search-cursor"});
await submit("pending");
await waitFor(`typeof window.__releaseSearch==='function'`);
assert.ok(!await evaluate(`document.body.textContent.includes('Loading videos')`));
await tab("Latest");
await waitFor(`document.querySelector('article')?.textContent.includes('video 0') && document.querySelectorAll('article').length===2`);
await evaluate(`window.__releaseSearch()`);
await evaluate(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
assert.ok(await evaluate(`document.querySelector('article').textContent.includes('video 0')`));
assert.ok(!await evaluate(`document.body.textContent.includes('use the loaded videos')`));
console.log("channel-wide search, upstream Popular, scoped pagination, view reset, and stale-query cancellation passed");
close();
