// Real local DASH media with two audio adaptations. Requires ffmpeg, Vite and dedicated Chrome.
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, basename } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import { send, evaluate, on, close } from './cdp.mjs';
const directory = mkdtempSync(join(tmpdir(), 'fanoos-audio-'));
const waitFor = condition => evaluate(`new Promise((resolve,reject)=>{const start=performance.now();function check(){if(${condition})return resolve();if(performance.now()-start>15000)return reject(Error('Audio check timed out: '+${JSON.stringify(condition)}));requestAnimationFrame(check)}check()})`);
let server;
try {
  execFileSync('ffmpeg', ['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=320x180:rate=24','-f','lavfi','-i','sine=frequency=440:sample_rate=48000','-f','lavfi','-i','sine=frequency=880:sample_rate=48000','-map','0:v','-map','1:a','-map','2:a','-t','30','-c:v','libx264','-preset','ultrafast','-g','48','-c:a','aac','-b:a','64k','-adaptation_sets','id=0,streams=v id=1,streams=1 id=2,streams=2','-f','dash',join(directory,'manifest.mpd')]);
  let manifest = readFileSync(join(directory,'manifest.mpd'),'utf8');
  for (const [id, language, label, role] of [['1','en','English (original)','main'],['2','fr','French dub','alternate']]) {
    manifest = manifest.replace(new RegExp(`<AdaptationSet id="${id}"([^>]*)>`), `<AdaptationSet id="${id}" lang="${language}"$1><Label>${label}</Label><Role schemeIdUri="urn:mpeg:dash:role:2011" value="${role}"/>`);
  }
  writeFileSync(join(directory,'manifest.mpd'),manifest);
  const files = new Set(readdirSync(directory));
  server = createServer((req,res)=>{
    const name=basename(new URL(req.url,'http://localhost').pathname);
    if(!files.has(name)){res.writeHead(404);res.end();return;}
    res.writeHead(200,{'access-control-allow-origin':'*','content-type':name.endsWith('.mpd')?'application/dash+xml':'video/mp4'});
    res.end(readFileSync(join(directory,name)));
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const mediaUrl=`http://127.0.0.1:${server.address().port}/manifest.mpd`;
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await send('Page.addScriptToEvaluateOnNewDocument',{source:readFileSync(new URL('./fixture.js',import.meta.url),'utf8')+`
  (()=>{const original=window.fetch;window.fetch=async(input,init)=>{
    const response=await original(input,init);
    if(new URL(input,location.href).pathname==='/api/me/data' && (init?.method??'GET')==='GET')return Response.json({data:{settings:{captions:true}}});
    if(new URL(input,location.href).pathname.startsWith('/api/v/youtube/videos/')){
      const page=await response.json();page.video.duration=30;page.stream={dash:${JSON.stringify(mediaUrl)},subtitles:[{id:'en-asr',locale:'en',label:'English (auto-generated)',autoGenerated:true,format:'vtt',url:'data:text/vtt,WEBVTT%0A%0A00:00.000%20--%3E%2000:30.000%0AAutomatic%20caption'}]};return Response.json(page);
    }return response;
  }})();`});
  const loaded=new Promise(resolve=>on('Page.loadEventFired',resolve));
  await send('Page.navigate',{url:process.env.PERF_URL||'http://127.0.0.1:5190/'});await loaded;
  await waitFor(`document.querySelector('a[href="/watch/youtube/v0"]')`);
  await evaluate(`document.querySelector('a[href="/watch/youtube/v0"]').click()`);
  await waitFor(`window.__dash?.getTracksFor('audio').length===2 && document.querySelector('video').readyState>=2`);
  assert.equal(await evaluate(`window.__dash.getCurrentTrackFor('audio').lang`),'en');
  await waitFor(`document.querySelector('video track')?.track.cues?.length===1`);
  await evaluate(`document.querySelector('video').currentTime=8`);
  await waitFor(`!document.querySelector('video').seeking`);
  const before=await evaluate(`({time:document.querySelector('video').currentTime,url:location.href})`);
  await evaluate(`document.querySelector('video').dispatchEvent(new Event('play'));document.querySelector('[aria-label="Settings"]').click()`);
  await waitFor(`document.querySelector('[role="menu"]')`);
  await evaluate(`[...document.querySelectorAll('[role="menu"] button')].find(b=>b.textContent.startsWith(' Audio')||b.textContent.trim().startsWith('Audio')).click()`);
  await waitFor(`[...document.querySelectorAll('[role="menu"] button')].some(b=>b.textContent.trim()==='French dub')`);
  await evaluate(`[...document.querySelectorAll('[role="menu"] button')].find(b=>b.textContent.trim()==='French dub').click()`);
  await waitFor(`window.__dash.getCurrentTrackFor('audio').lang==='fr'`);
  const after=await evaluate(`({time:document.querySelector('video').currentTime,paused:document.querySelector('video').paused,url:location.href})`);
  assert.equal(after.paused,true);assert.equal(after.url,before.url);assert.ok(Math.abs(after.time-before.time)<0.5);
  await evaluate(`document.querySelector('video').muted=true;document.querySelector('video').play()`);
  await waitFor(`document.querySelector('video').currentTime>9`);
  await evaluate(`[...document.querySelectorAll('[role="menu"] button')].find(b=>b.textContent.trim()==='English (original)').click()`);
  await waitFor(`window.__dash.getCurrentTrackFor('audio').lang==='en' && document.querySelector('video').currentTime>10`);
  assert.equal(await evaluate(`document.querySelector('video').paused`),false);
  await evaluate(`document.querySelector('[aria-label$="(c)"]').click()`);
  await waitFor(`[...document.querySelectorAll('[role="menu"] button')].some(b=>b.textContent.trim()==='English (auto-generated)')`);
  await evaluate(`[...document.querySelectorAll('[role="menu"] button')].find(b=>b.textContent.trim()==='English (auto-generated)').click()`);
  await waitFor(`document.querySelector('video track')?.track.activeCues?.length===1`);
  await evaluate(`document.querySelector('[aria-label="Settings"]').click()`);
  await waitFor(`!document.querySelector('[role="menu"]')`);
  const shot=await send('Page.captureScreenshot',{format:'png'});
  writeFileSync('/tmp/tube-player-audio.png',Buffer.from(shot.data,'base64'));
  console.log('PASS: real DASH paused/playing audio switching preserves position and URL; VTT cue renders');
} finally {
  close();
  if(server)await new Promise(resolve=>server.close(resolve));
  rmSync(directory,{recursive:true,force:true});
}
