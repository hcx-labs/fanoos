import assert from "node:assert/strict";
import { test } from "node:test";
import type { MediaInfo } from "dashjs";
import { initialSubtitle, subtitleKey, audioOptions, audioKey, preferredAudio } from "./player-tracks.ts";
const tracks = [
  { id: "en-asr", locale: "en-US", label: "English auto", autoGenerated: true, format: "vtt" as const, url: "/auto" },
  { id: "en-manual", locale: "en-US", label: "English", format: "vtt" as const, url: "/manual" },
];
test("caption defaults, explicit off, manual preference and real language keys", () => {
  assert.equal(initialSubtitle(tracks, undefined, undefined, false, ["en-US"]), "");
  assert.equal(initialSubtitle(tracks, "", undefined, true, ["en-US"]), "");
  assert.equal(initialSubtitle(tracks, "en-US", undefined, false, ["fr"]), "en-manual");
  assert.equal(initialSubtitle(tracks, undefined, "en", true, ["en-US"]), "en-manual");
  assert.equal(initialSubtitle(tracks, undefined, "ja", true, ["en-GB"]), "en-manual");
  assert.equal(initialSubtitle(tracks.slice(0, 1), "en-US", undefined, true, []), "en-asr");
  assert.equal(initialSubtitle(tracks, "de", undefined, true, []), "");
  assert.notEqual(subtitleKey(tracks[0]!), subtitleKey(tracks[1]!));
  const ass = { locale: "en-US", label: "English", format: "ass" as const, url: "/english.ass" };
  assert.equal(initialSubtitle([ass], "en-US", "ja", true, []), "en-US");
});
const audio = (id: string, lang: string, label: string, role: string, codec = "opus") => ({ id, lang, labels: [{ text: label }], roles: [{ value: role }], codec }) as MediaInfo;
test("DASH codec alternatives deduplicate, roles/labels remain distinct, preferences default to main", () => {
  const en = audio("1", "en", "English", "main");
  const options = audioOptions([audio("0", "fr", "French", "alternate"), en, audio("2", "en", "English", "main", "mp4a"), audio("3", "en", "Description", "alternate")]);
  assert.equal(options.length, 3);
  assert.equal(preferredAudio(options)?.key, audioKey(en));
  assert.equal(preferredAudio(options, "de")?.key, audioKey(en));
  assert.equal(preferredAudio(options, "en-US")?.key, audioKey(en));
  assert.equal(preferredAudio(options, "fr")?.language, "fr");
  assert.equal(preferredAudio([]), undefined);
});
