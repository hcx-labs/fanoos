import type { MediaInfo } from "dashjs";
import type { Subtitle } from "./types";

export const subtitleKey = (track: Pick<Subtitle, "id" | "locale">) => track.id ?? track.locale;
const base = (language: string) => language.toLowerCase().split("-")[0];

/** Saved values are languages (or explicit off), never service track IDs. */
export function initialSubtitle(tracks: Subtitle[], saved: string | undefined, audio: string | undefined, captions: boolean, languages: readonly string[]): string {
  if (saved === "" || (saved === undefined && !captions)) return "";
  const ordered = [...tracks].sort((a, b) => Number(Boolean(a.autoGenerated)) - Number(Boolean(b.autoGenerated)));
  for (const language of saved === undefined ? [...languages, ...(audio ? [audio] : [])] : [saved]) {
    const track = ordered.find((t) => t.locale.toLowerCase() === language.toLowerCase())
      ?? ordered.find((t) => base(t.locale) === base(language));
    if (track) return subtitleKey(track);
  }
  return saved === undefined && ordered[0] ? subtitleKey(ordered[0]) : "";
}

export type AudioOption = { key: string; label: string; language: string; main: boolean; track: MediaInfo };
export function audioKey(track: MediaInfo): string {
  return JSON.stringify([track.lang?.toLowerCase() ?? "", (track.labels ?? []).map((l) => l.text).sort(), (track.roles ?? []).map((r) => r.value).sort()]);
}
export function audioOptions(tracks: MediaInfo[]): AudioOption[] {
  const options = new Map<string, AudioOption>();
  for (const track of tracks) {
    const key = audioKey(track);
    if (!options.has(key)) options.set(key, { key, label: track.labels?.[0]?.text || track.lang || "Original", language: track.lang ?? "", main: Boolean(track.roles?.some((r) => r.value === "main")), track });
  }
  return [...options.values()];
}
export function preferredAudio(options: AudioOption[], saved?: string, current?: string): AudioOption | undefined {
  const mainFirst = [...options].sort((a, b) => Number(b.main) - Number(a.main));
  return (saved ? mainFirst.find((o) => o.language.toLowerCase() === saved.toLowerCase())
    ?? mainFirst.find((o) => base(o.language) === base(saved)) : undefined)
    ?? mainFirst.find((o) => o.main) ?? mainFirst.find((o) => o.key === current) ?? mainFirst[0];
}

/** Only the selected VTT is attached. Disable before removing, including while loading. */
export function attachVtt(video: HTMLVideoElement, subtitle: Subtitle, onError?: () => void): () => void {
  const track = document.createElement("track");
  track.kind = "subtitles";
  track.label = subtitle.label;
  track.srclang = subtitle.locale;
  track.src = subtitle.url;
  // Keep unpositioned captions above our custom controls. Preserve authored positions.
  const position = () => {
    for (const cue of Array.from(track.track.cues ?? [])) {
      if (cue instanceof VTTCue && cue.line === "auto") cue.line = -4;
    }
  };
  track.addEventListener("load", position);
  if (onError) track.addEventListener("error", onError);
  video.append(track);
  track.track.mode = "showing";
  return () => {
    track.removeEventListener("load", position);
    if (onError) track.removeEventListener("error", onError);
    track.track.mode = "disabled";
    track.remove();
  };
}
